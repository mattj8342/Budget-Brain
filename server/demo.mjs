import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {calculatePaycheck} from './allocation.mjs';
import {normalizeTarget} from './target-semantics.mjs';
const read=async path=>JSON.parse(await readFile(new URL(path,import.meta.url),'utf8'));
const [settings,snapshot,ids]=await Promise.all([read('../examples/household/settings.json'),read('../examples/demo/snapshot.json'),read('../examples/demo/ids.json')]);
const result=calculatePaycheck({snapshot,policy:settings.allocation_policy,payday:'2027-04-09',next_payday:'2027-04-23',weekly_contributions:[{category_id:ids.therapy,already_contributed_milliunits:10000}],card_gap_reviews:[ids.card],remaining_choices:[{category_id:ids.travel,amount_milliunits:100000},{category_id:ids.clothes,amount_milliunits:15000}]});
assert.equal(result.status,'calculated');
assert.equal(result.assigned_milliunits+result.remaining_milliunits,snapshot.ready_to_assign);
assert.equal(result.remaining_milliunits,0);
assert.ok(!result.rows.some(row=>row.category_id===ids.work));
assert.equal(result.rows.find(row=>row.category_id===ids.food).change_milliunits,120000);
assert.equal(result.rows.find(row=>row.category_id===ids.therapy).change_milliunits,40000);
const clothing=normalizeTarget(snapshot.categories.find(c=>c.id===ids.clothes));
assert.equal(clothing.every,3);
console.log('BUDGET BRAIN: FICTIONAL PAYDAY DEMO');
console.table(result.rows.map(row=>({category:row.name,added:row.change_milliunits/1000,available:row.projected_available_milliunits/1000})));
console.log(JSON.stringify({status:result.status,assigned:result.assigned_milliunits/1000,remaining:result.remaining_milliunits/1000,clothing_repeats_every_months:clothing.every,excluded_work_balance_untouched:true},null,2));
console.log('Offline calculation only. No credentials, saved plan, or YNAB requests.');
